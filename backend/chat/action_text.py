"""Русские формы фразы действия для отправителя и адресата.

«подмигивает» → «Вы подмигиваете {whom}» и «Вам подмигивает {who}». Глагол
меняем по первому слову (дальше — дополнение: «посылает лучи добра»); если
фраза кончается предлогом («кинул тапок в», «глядя на»), местоимение встаёт
после него в нужном падеже: «{who} кинул тапок в вас». Тот же алгоритм — в
клиенте (src/lib/actionText.ts), чтобы форма админа показывала то же.
"""

# Окончание 3-го лица (или прошедшего времени) → форма для «вы».
_ENDINGS = [
    ("ется", "етесь"), ("ётся", "ётесь"), ("ится", "итесь"), ("ался", "ались"), ("ялся", "ялись"), ("ился", "ились"),
    ("ёт", "ёте"), ("ет", "ете"), ("ит", "ите"), ("ут", "ете"), ("ют", "ете"), ("ат", "ите"), ("ят", "ите"),
    ("ла", "ли"), ("ло", "ли"), ("л", "ли"),
]

# Предлог в конце фразы → «вы» в нужном падеже.
_PREP = {
    "в": "вас", "во": "вас", "на": "вас", "за": "вас", "про": "вас", "через": "вас", "сквозь": "вас",
    "из-за": "вас", "у": "вас", "для": "вас", "от": "вас", "без": "вас", "около": "вас", "возле": "вас", "из": "вас", "до": "вас",
    "к": "вам", "ко": "вам", "по": "вам",
    "с": "вами", "со": "вами", "над": "вами", "под": "вами", "перед": "вами", "между": "вами",
    "о": "вас", "об": "вас", "обо": "вас", "при": "вас",
}


def verb_you(verb):
    """«подмигивает» → «подмигиваете», «кинул тапок в» → «кинули тапок в»."""
    verb = (verb or "").strip()
    head, sep, rest = verb.partition(" ")
    low = head.lower()
    for end, rep in _ENDINGS:
        if low.endswith(end):
            head = head[: len(head) - len(end)] + rep
            break
    return head + (sep + rest if sep else "")


def trailing_prep(verb):
    last = (verb or "").strip().rsplit(" ", 1)[-1].lower().strip(",")
    return last if last in _PREP else ""


def ru_self(verb, solo=False):
    """Отправителю: «Вы подмигиваете {whom}»; без адресата (solo) — «Вы запомнили это»."""
    return f"Вы {verb_you(verb)}" if solo else f"Вы {verb_you(verb)} {{whom}}"


def ru_you(verb, acc=False):
    """Адресату: «Вам подмигивает {who}» / «Вас обнимает {who}» / «{who} кинул тапок в вас»."""
    verb = (verb or "").strip()
    prep = trailing_prep(verb)
    if prep:
        return f"{{who}} {verb} {_PREP[prep]}"
    return f"{'Вас' if acc else 'Вам'} {verb} {{who}}"
