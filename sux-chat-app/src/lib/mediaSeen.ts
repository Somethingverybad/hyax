/**
 * Вложения, которые уже показывались в этой сессии (картинка в ленте, постер
 * видео). Браузер держит их в памяти, и при повторном монтировании — возврат
 * на вкладку, другой чат и обратно — они рисуются сразу; скелетон загрузки
 * для них только мелькает (баг-репорт 08f7f108). Ключ — маркер файла (s3://…
 * или путь), а не подписанная ссылка: подпись у одного файла меняется.
 */
const seen = new Set<string>();

export const markMediaSeen = (key?: string | null) => { if (key) seen.add(key); };
export const mediaSeen = (key?: string | null) => !!key && seen.has(key);
