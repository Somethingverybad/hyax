/**
 * Есть ли токен входа. Экраны раньше при любой ошибке загрузки профиля
 * уводили на /auth, а вход с живым токеном тут же возвращал на /chat: при
 * моргающей сети это крутилось по кругу каждые 5 с и выглядело как «постоянно
 * выкидывает в список чатов» (баг-репорт a561358d). На вход уводим только без
 * токена; отозванную или протухшую сессию обрабатывает lib/forceLogout сам.
 */
export const signedIn = (): boolean => { try { return !!localStorage.getItem("access_token"); } catch { return false; } };
